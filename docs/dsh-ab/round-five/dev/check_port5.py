#!/usr/bin/env python3
"""Classify every changed line of the round-five port and write the full diffs (standard library only).

    python dev/check_port5.py    -> port-diff.txt (full unified diffs, ab4 file vs ab5 file) and
                                    dev/port5-classify.json; prints one summary line per file

For each ported file, every line that differs from its ab4 source is classified:
  mechanical  the line is a changed line whose ab4 text, passed through port5.py's replacement rules on its own,
              gives exactly the ab5 text (so the change is one of the listed replacements);
  hand        anything else (a line added, removed, or changed beyond the rules); these are the hand edits that
              PORT.md lists one by one.
The second part of port-diff.txt holds the generated round files against their sources: the change-5 rule files
against W:\\Projects\\gravitas-round5\\dist\\<lang>\\gravitas\\rules\\AGENTS.md, and the overlays, expected-rule-hashes.json
and schedules against round four's.
"""
import difflib
import hashlib
import json
import os
import sys

DEV = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, DEV)
sys.dont_write_bytecode = True
import port5  # noqa: E402

SRC, DST = port5.SRC, port5.DST
W = r"W:\Projects\gravitas-round5"


def lines(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read().splitlines(keepends=True)


def udiff(a_path, b_path, a_label, b_label):
    a, b = lines(a_path), lines(b_path)
    out = list(difflib.unified_diff(a, b, a_label, b_label, n=3))
    return "".join(x if x.endswith("\n") else x + "\n\\ No newline at end of file\n" for x in out)


def classify(src, dst, frozen_new):
    a, b = lines(os.path.join(SRC, src)), lines(os.path.join(DST, dst))
    sm = difflib.SequenceMatcher(a=a, b=b, autojunk=False)
    mech, hand = 0, []
    removed = added = 0
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "equal":
            continue
        removed += i2 - i1
        added += j2 - j1
        if tag == "replace" and (i2 - i1) == (j2 - j1):
            for k in range(i2 - i1):
                old, new = a[i1 + k], b[j1 + k]
                ported, _ = port5.port_text(src, old, frozen_new if src in ("verdict4-amended.py", "mutation4.py") else None)
                if ported == new:
                    mech += 1
                else:
                    hand.append({"ab4_line": i1 + k + 1, "ab5_line": j1 + k + 1, "old": old.rstrip("\n"), "new": new.rstrip("\n")})
        else:
            # lines added or removed, or a block whose size changed: try to pair them by the rules first
            olds, news = a[i1:i2], b[j1:j2]
            ported = [port5.port_text(src, o, frozen_new if src in ("verdict4-amended.py", "mutation4.py") else None)[0] for o in olds]
            matched_new = set()
            for o, p in zip(olds, ported):
                if p in news and news.index(p) not in matched_new:
                    matched_new.add(news.index(p))
                    mech += 1
                else:
                    hand.append({"ab4_line": i1 + olds.index(o) + 1, "ab5_line": None, "old": o.rstrip("\n"), "new": None})
            for idx, n in enumerate(news):
                if idx not in matched_new:
                    hand.append({"ab4_line": None, "ab5_line": j1 + idx + 1, "old": None, "new": n.rstrip("\n")})
    return {"removed": removed, "added": added, "mechanical_pairs": mech, "hand": hand}


def main():
    frozen_new = hashlib.sha256(open(os.path.join(DST, "verdict5.py"), "rb").read()).hexdigest()
    parts = ["Round five port: full unified diffs, round four's file (ab4) against round five's (ab5).",
             "Generated by dev/check_port5.py. Part 1: the ported scripts. Part 2: the generated round files.", ""]
    report = {}
    parts.append("=" * 100)
    parts.append("PART 1: ported scripts (W:\\AgentData\\logs\\gravitas-dsh-ab4\\<file> vs W:\\AgentData\\logs\\gravitas-dsh-ab5\\<file>)")
    parts.append("=" * 100)
    for src, dst in port5.FILES.items():
        c = classify(src, dst, frozen_new)
        report[dst] = dict(c, source=src)
        d = udiff(os.path.join(SRC, src), os.path.join(DST, dst), "ab4/" + src, "ab5/" + dst)
        parts.append("")
        parts.append("#" * 100)
        parts.append("# %s  <-  %s   (%d lines removed, %d added; %d changed lines explained by the replacement rules; "
                     "%d hand-edit lines)" % (dst, src, c["removed"], c["added"], c["mechanical_pairs"], len(c["hand"])))
        parts.append("#" * 100)
        parts.append(d.rstrip("\n") if d else "(byte-identical)")
        print("%-22s <- %-22s -%-4d +%-4d mechanical %-4d hand %d" % (dst, src, c["removed"], c["added"], c["mechanical_pairs"],
                                                                    len(c["hand"])))
    parts.append("")
    parts.append("=" * 100)
    parts.append("PART 2: generated round files against their sources")
    parts.append("=" * 100)
    gen = [(os.path.join(W, "dist", l, "gravitas", "rules", "AGENTS.md"), os.path.join(DST, "rules", "change5", l + ".md"),
            "gravitas-round5/dist/%s/gravitas/rules/AGENTS.md" % l, "ab5/rules/change5/%s.md" % l) for l in ("en", "zh-CN", "ja", "ko")]
    for s in ("zh", "en", "ja", "ko"):
        gen.append((os.path.join(SRC, "overlays", "base-%s.yml" % s), os.path.join(DST, "overlays", "base-%s.yml" % s),
                    "ab4/overlays/base-%s.yml" % s, "ab5/overlays/base-%s.yml" % s))
        gen.append((os.path.join(SRC, "overlays", "c4-%s.yml" % s), os.path.join(DST, "overlays", "c5-%s.yml" % s),
                    "ab4/overlays/c4-%s.yml" % s, "ab5/overlays/c5-%s.yml" % s))
    gen.append((os.path.join(SRC, "expected-rule-hashes.json"), os.path.join(DST, "expected-rule-hashes.json"),
                "ab4/expected-rule-hashes.json", "ab5/expected-rule-hashes.json"))
    gen.append((os.path.join(SRC, "tuning-schedule.txt"), os.path.join(DST, "tuning-schedule-1.txt"),
                "ab4/tuning-schedule.txt", "ab5/tuning-schedule-1.txt"))
    gen.append((os.path.join(SRC, "tuning-schedule.txt"), os.path.join(DST, "tuning-schedule-2.txt"),
                "ab4/tuning-schedule.txt", "ab5/tuning-schedule-2.txt"))
    for a, b, la, lb in gen:
        d = udiff(a, b, la, lb)
        parts.append("")
        parts.append("#" * 100)
        parts.append("# %s  <-  %s" % (lb, la))
        parts.append("#" * 100)
        parts.append(d.rstrip("\n") if d else "(byte-identical)")
    parts.append("")
    parts.append("(schedule.txt is new for round five, not a port: 72 lines from dev/make_schedule5.py with the seed in "
                 "schedule.seed.txt; round four's schedule.txt held round four's cases, so no diff is given.)")
    with open(os.path.join(DST, "port-diff.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(parts) + "\n")
    with open(os.path.join(DEV, "port5-classify.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(report, f, ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main()
